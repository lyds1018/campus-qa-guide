def _blocks_of(md: str) -> list[tuple[str, int]]:
    blocks: list[tuple[str, int]] = []
    buf: list[str] = []
    for line in md.splitlines():
        s = line.strip()
        if s.startswith("#"):
            if buf:
                blocks.append(("\n".join(buf), 0))
                buf = []
            level = len(s) - len(s.lstrip("#"))
            blocks.append((s.lstrip("#").strip(), min(level, 2)))
        elif not s:
            if buf:
                blocks.append(("\n".join(buf), 0))
                buf = []
        else:
            buf.append(s)
    if buf:
        blocks.append(("\n".join(buf), 0))
    return blocks


def write_pdf(md: str, path: Path) -> None:
    doc = fitz.open()
    top, bottom, left, right = 60, 780, 60, 535

    def new_page():
        return doc.new_page(width=595, height=842)

    page = new_page()
    y = top

    for text, level in _blocks_of(md):
        size = {0: BODY, 1: H1, 2: H2}[level]
        gap = {0: 6, 1: 12, 2: 8}[level]

        # 剩余空间不足两行就翻页，避免生成空/负高度文本框
        if y + size * 3.2 > bottom:
            page = new_page()
            y = top

        rect = fitz.Rect(left, y, right, bottom)
        rc = page.insert_textbox(
            rect, text, fontname="china-s", fontsize=size, lineheight=1.55, align=0
        )
        if rc < 0:  # 本页放不下，翻页重排
            page = new_page()
            y = top
            rect = fitz.Rect(left, y, right, bottom)
            rc = page.insert_textbox(
                rect, text, fontname="china-s", fontsize=size, lineheight=1.55, align=0
            )
            if rc < 0:
                print(f"[warn] 段落超页被跳过：{text[:20]}")
                continue
        y = bottom - rc + gap

    doc.save(path)
    doc.close()


