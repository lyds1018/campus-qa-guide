def main() -> None:
    if ROOT.exists():
        shutil.rmtree(ROOT)
    dirs = {k: ROOT / k for k in ("guide", "policy", "faq", "notice")}
    for d in dirs.values():
        d.mkdir(parents=True)

    guide_pdf = {1, 6, 13, 17, 24}   # 学生证、转专业、学位证、VPN、档案
    policy_pdf = {1, 2, 4, 7, 10}    # 学籍、考场纪律、实验室、学位授予、助学贷款

    count = 0
    for i, g in enumerate(GUIDES, 1):
        md = render_guide(g)
        stem = f"{i:02d}-{g['name']}"
        if i in guide_pdf:
            write_pdf(md, dirs["guide"] / f"{stem}.pdf")
        else:
            (dirs["guide"] / f"{stem}.md").write_text(md, encoding="utf-8")
        count += 1

    for i, p in enumerate(POLICIES, 1):
        md = render_policy(p)
        stem = f"{i:02d}-{p['title']}"
        if i in policy_pdf:
            write_pdf(md, dirs["policy"] / f"{stem}.pdf")
        else:
            (dirs["policy"] / f"{stem}.md").write_text(md, encoding="utf-8")
        count += 1

    for i, f in enumerate(FAQS, 1):
        md = render_faq(f)
        (dirs["faq"] / f"{i:02d}-{f['topic']}.md").write_text(md, encoding="utf-8")
        count += 1

    for i, n in enumerate(NOTICES, 1):
        md = render_notice(n)
        write_pdf(md, dirs["notice"] / f"{i:02d}-{n['title']}.pdf")
        count += 1

    files = sorted(ROOT.rglob("*.*"))
    pdfs = [f for f in files if f.suffix == ".pdf"]
    print(f"生成 {count} 份，文件 {len(files)} 个，其中 PDF {len(pdfs)} 个")
    print(f"输出目录：{ROOT}")


if __name__ == "__main__":
    main()
