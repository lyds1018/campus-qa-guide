def render_policy(p: dict) -> str:
    parts = [f"# {p['title']}", "", f"（{p['dept']}发布）", ""]
    for chapter, clauses in p["chapters"]:
        parts.append(f"## {chapter}")
        parts.append("")
        for c in clauses:
            parts.append(c)
            parts.append("")
    return "\n".join(parts)


def render_faq(f: dict) -> str:
    parts = [f"# {f['topic']}", "", "以下问题由教务处、学生工作处等相关部门的常见咨询整理而成。", ""]
    for i, (q, a) in enumerate(f["items"], 1):
        parts.append(f"## 问题{i}：{q}")
        parts.append("")
        parts.append(a)
        parts.append("")
    return "\n".join(parts)


def render_notice(n: dict) -> str:
    parts = [f"# {n['title']}", ""]
    for line in n["body"]:
        parts.append(line)
        parts.append("")
    return "\n".join(parts)


